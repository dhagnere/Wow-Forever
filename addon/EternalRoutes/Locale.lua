local function apply(lang)
    local src = (lang == "en") and EN or FR
    for k, v in pairs(src) do L[k] = v end
end

function ns.SetLang(lang)
    ns.lang = (lang == "en") and "en" or "fr"
    if ns.db then ns.db.lang = ns.lang end
    apply(ns.lang)
    if ns.Window and ns.Window.OnLanguageChanged then
        ns.Window.OnLanguageChanged()
    end
end

function ns.IsEnglish()
    return ns.lang == "en"
end

local initial = (GetLocale() == "enUS" or GetLocale() == "enGB") and "en" or "fr"
ns.lang = initial
apply(initial)
